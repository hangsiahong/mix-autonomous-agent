#!/bin/bash
# core/mix/22_process_one_tool_call.sh — single-tool dispatcher.
#
# `process_tc <chat_id> <msg_id> <tc_json> <thread_id>` is called once per
# tool call when the agent's response includes one or many. It:
#   1. Parses the tool name + arguments from the OpenAI-format `tool_calls`
#      entry the model produced.
#   2. Enforces per-turn caps (loop detection, idempotent vs mutating
#      classification, hard caps per tool category).
#   3. Updates the Telegram working message with a live status line
#      (`🔧 <name>` → `✓ <name>: <preview>`) unless AMA_PARALLEL=true
#      (then 23_parallel_tools.sh owns display).
#   4. Calls `run_tool` (13_tool_execution.sh) to actually execute.
#   5. Sends generated photos via tg_send_photo for image_generate output.
#   6. Returns the tool output for the caller to append_tool_result into
#      history.

process_tc() {
    local chat_id="$1"
    local msg_id="$2"
    local tc_json="$3" # Single tool call object
    local thread_id="$4"
    
    # Parse tool name and arguments using Python for robust handling
    local py_out
    py_out=$(python3 -c '
import sys, json
try:
    tc = json.loads(sys.argv[1])
    name = tc.get("function", {}).get("name") or tc.get("name", "")
    args = tc.get("function", {}).get("arguments") or tc.get("args", "{}")
    if isinstance(args, str):
        try:
            # check if it is valid json string
            json.loads(args)
        except:
            args = "{}"
    else:
        args = json.dumps(args)
        
    print(f"NAME={name.strip()}")
    print(f"ARGS={args}")
except Exception as e:
    print("NAME=unknown_tool")
    print("ARGS={}")
' "$tc_json")

    local name=$(echo "$py_out" | grep "^NAME=" | cut -d= -f2-)
    local args=$(echo "$py_out" | grep "^ARGS=" | cut -d= -f2-)
    
    if [[ -z "$name" || "$name" == "unknown_tool" ]]; then
        echo "Error: Tool name could not be parsed from JSON."
        return
    fi
    
    # 1. Guardrail: Detect loops (same tool + same args in same turn)
    local args_hash=$(echo "$args" | sha256sum | awk '{print $1}')
    local call_sig="${name}_${args_hash}"

    # 2. Per-tool call cap
    local _idempotent_tools="read_code list_files web_search fetch_url memory_recall check_health sys_info context_discovery repo_map read_error_log insights search_files session_search recap browser"
    local _mutating_tools="edit_code patch write_file memory_remember custom_tool_manager skill_manager skill_install image_generate autonomy"
    local tool_cap=3
    if echo " $_idempotent_tools " | grep -qw "$name"; then
        tool_cap=8
    elif echo " $_mutating_tools " | grep -qw "$name"; then
        tool_cap=3
    elif [[ "$name" == "bash" ]]; then
        tool_cap=6
    fi

    local name_count=0
    name_count=$(echo "$TURN_CALLS" | tr ' ' '\n' | grep -c "^${name}_" 2>/dev/null) || name_count=0
    if [[ $name_count -ge $tool_cap ]]; then
        echo "Error: You have already called '$name' ${name_count} times this turn (limit: $tool_cap). Do not retry further — answer using what you already have."
        return
    fi

    # Track calls in turn scope
    if [[ "$TURN_CALLS" == *"$call_sig"* ]]; then
        echo "Error: Loop detected! You already called $name with these exact arguments. Do not retry."
        return
    fi
    TURN_CALLS="$TURN_CALLS $call_sig"

    # ── Extract key argument for status display ────
    local key_arg
    key_arg=$(echo "$args" | python3 -c "
import json, sys
try:
    a = json.loads(sys.stdin.read())
    for k in ['query', 'path', 'command', 'url', 'file_path', 'name',
              'target', 'action', 'input', 'text', 'topic', 'search']:
        if k in a:
            v = str(a[k]).replace('\\n',' ').strip()[:80]
            v = v.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')
            print(v)
            break
except: pass
" 2>/dev/null)

    # ── Show running status ────────────────────────────────
    local _prefix="${_AMA_REASONING_HTML:+${_AMA_REASONING_HTML}&#10;&#10;}"
    if [[ "$AMA_PARALLEL" != "true" ]]; then
        if [[ -n "$key_arg" ]]; then
            tg_edit "$chat_id" "$msg_id" "${_prefix}🔧 <code>${name}</code> <i>${key_arg}</i>" "HTML" > /dev/null 2>&1
        else
            tg_edit "$chat_id" "$msg_id" "${_prefix}🔧 <code>${name}</code>" "HTML" > /dev/null 2>&1
        fi
    fi

    log_tool_usage "$chat_id" "$name"
    local output
    output=$(run_tool "$name" "$args" "$chat_id" "$thread_id")

    # Check for image attachment — match the new image.pollinations.ai endpoint
    # AND the legacy pollinations.ai/p/ form so any older cached output still
    # works during transitions.
    if [[ "$name" == "image_generate" ]]; then
        local img_url
        img_url=$(echo "$output" | grep -oE 'https://(image\.)?pollinations\.ai/(prompt|p)/[^ )]+' | head -1)
        [[ -n "$img_url" ]] && tg_send_photo "$chat_id" "$img_url" "Generated by $name" > /dev/null
    fi

    # ── Show a one-line preview ────────────────────────────
    if [[ "$AMA_PARALLEL" != "true" ]]; then
        local preview
        preview=$(printf '%s' "$output" | grep -v '^[[:space:]]*$' | head -1 | head -c 120)
        if [[ -n "$preview" ]]; then
            local esc_preview
            esc_preview=$(printf '%s' "$preview" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g')
            tg_edit "$chat_id" "$msg_id" "${_prefix}✅ <code>${name}</code>: <i>${esc_preview}</i>" "HTML" > /dev/null 2>&1
        fi
    fi

    echo "$output"
}
